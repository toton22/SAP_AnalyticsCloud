#!/usr/bin/env python3
"""
Rebuild uploads/manifest.json and uploads/manifest.js from whatever is in uploads/.

Run it locally (python scripts/build_manifest.py) or let the GitHub Action run it
on every push that touches uploads/. The Uploads page reads manifest.js, so the
site needs no server and works from file:// as well as from GitHub Pages.

Rules:
  * every file under uploads/ is listed, except the manifest itself, README/notes
    that start with a dot or underscore, and anything in a folder starting with "_"
  * the first folder level is the "collection" (e.g. 2026-10-02-sap-ucc-sac-workshop)
  * the second folder level, if any, is the "group" inside that collection
  * the date shown is the last git commit that touched the file, falling back to mtime
"""
import json, os, subprocess, sys, time, re
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UP = os.path.join(ROOT, "uploads")
SKIP_NAMES = {"manifest.json", "manifest.js", "README.md", ".gitkeep", ".DS_Store", "Thumbs.db"}

KIND = {
    "image": {"png", "jpg", "jpeg", "gif", "webp", "svg", "avif"},
    "slides": {"pptx", "ppt", "key", "odp"},
    "doc": {"pdf", "docx", "doc", "odt", "rtf"},
    "sheet": {"xlsx", "xls", "csv", "ods", "tsv"},
    "notes": {"md", "txt", "markdown"},
    "video": {"mp4", "mov", "webm", "m4v"},
    "audio": {"mp3", "m4a", "wav", "ogg"},
    "archive": {"zip", "7z", "rar", "tar", "gz"},
    "code": {"html", "js", "py", "json", "ipynb", "sql", "css"},
}


def kind_of(ext):
    for k, exts in KIND.items():
        if ext in exts:
            return k
    return "other"


def git_date(rel):
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cI", "--", rel],
            cwd=ROOT, capture_output=True, text=True, timeout=20,
        ).stdout.strip()
        return out or None
    except Exception:
        return None


def pretty(name):
    """'2026-10-02-sap-ucc-sac-workshop' -> ('2026-10-02', 'Sap Ucc Sac Workshop')"""
    m = re.match(r"^(\d{4}-\d{2}-\d{2})[-_ ]?(.*)$", name)
    date, rest = (m.group(1), m.group(2)) if m else (None, name)
    words = re.sub(r"[-_]+", " ", rest).strip()
    # keep known acronyms loud
    words = " ".join(w.upper() if w.lower() in {"sap", "ucc", "sac", "ua", "bw", "c_sac"} else w.capitalize()
                     for w in words.split())
    return date, words or name


def main():
    if not os.path.isdir(UP):
        print("no uploads/ folder", file=sys.stderr)
        sys.exit(1)
    files = []
    for dirpath, dirnames, filenames in os.walk(UP):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith((".", "_")))
        for fn in sorted(filenames):
            if fn in SKIP_NAMES or fn.startswith((".", "_")):
                continue
            full = os.path.join(dirpath, fn)
            rel_up = os.path.relpath(full, UP).replace(os.sep, "/")
            rel_root = os.path.relpath(full, ROOT).replace(os.sep, "/")
            parts = rel_up.split("/")
            collection = parts[0] if len(parts) > 1 else ""
            group = parts[1] if len(parts) > 2 else ""
            ext = fn.rsplit(".", 1)[-1].lower() if "." in fn else ""
            st = os.stat(full)
            when = git_date(rel_root) or datetime.fromtimestamp(st.st_mtime, timezone.utc).isoformat(timespec="seconds")
            files.append({
                "path": rel_up,
                "name": fn,
                "collection": collection,
                "group": group,
                "ext": ext,
                "kind": kind_of(ext),
                "size": st.st_size,
                "modified": when,
            })

    collections = {}
    for f in files:
        c = f["collection"]
        if c not in collections:
            date, title = pretty(c) if c else (None, "Loose files")
            collections[c] = {"id": c, "title": title, "date": date, "count": 0, "bytes": 0}
        collections[c]["count"] += 1
        collections[c]["bytes"] += f["size"]

    manifest = {
        "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "root": "uploads",
        "collections": sorted(collections.values(), key=lambda c: (c["date"] or "", c["id"]), reverse=True),
        "files": files,
    }
    with open(os.path.join(UP, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
    with open(os.path.join(UP, "manifest.js"), "w", encoding="utf-8") as fh:
        fh.write("/* generated by scripts/build_manifest.py — do not edit by hand */\n")
        fh.write("window.UPLOADS_MANIFEST = ")
        json.dump(manifest, fh, ensure_ascii=False)
        fh.write(";\n")
    print(f"manifest: {len(files)} files in {len(collections)} collection(s)")


if __name__ == "__main__":
    main()
